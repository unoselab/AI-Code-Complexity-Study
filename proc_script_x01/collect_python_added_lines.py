#!/usr/bin/env python3
"""Collect monthly physical lines added in tracked Python files.

This is the self-contained collection stage for run-x-b02-v4. It reproduces
repository-month activity from a frozen repository history tip and computes the
Python-only flow outcome used by the later DiD analysis.

Measurement contract
--------------------
- Commit universe: commits reachable from a repository-level history tip SHA
  resolved once from the configured history ref at repository start.
- Month assignment: Git committer timestamp in the configured timezone.
- Broad outcome: compare every non-root commit with its first parent, including
  merge commits for backward compatibility with v3.
- Cleaned outcomes: exclude merge commits while retaining reachable branch
  commits in their original committer month.
- Root commits: count the commit, but exclude root additions from line metrics.
- Python scope: post-change regular files whose path ends in .py and whose
  directory is not excluded by the configured run-x-b02 policy.
- Source scope: exclude explicit vendor and conservative generated path markers;
  tests remain in the primary source outcome and are excluded in a sensitivity
  outcome only.
- Metric: physical added lines reported by Git numstat. Blank lines, comments,
  and docstrings are included because this is a development-flow metric.
- No-commit months receive zero activity. Monthly activity is never carried
  forward.

The script never checks out, resets, cleans, fetches, pulls, or modifies a
repository clone.
"""

