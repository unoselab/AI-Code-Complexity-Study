#!/usr/bin/env python3
"""Prepare Borusyak DiD inputs for NPR-based commit-function AGC outcomes.

This stage consumes the complete repository-month table generated by
run-py-7a and joins the covariates used by the existing commit-function
Borusyak workflow. It does not estimate treatment effects.

Scientific scope
----------------
The default specification, ``range100_200``, includes only function-change
events whose implementation body contains 100-200 literal-space tokens and
was successfully scored by the frozen DetectCodeGPT NPR pipeline.

The full-sample count outcomes retain every repository-month, including months
with zero NPR-selected events. The AGC ratio outcome is defined only when at
least one NPR-selected event is present and is therefore interpreted as a
conditional composition outcome.

Competing NCLOC specifications
------------------------------
The paper-compatible and Python-snapshot NCLOC variables are preserved as two
alternative model specifications. They must never be entered together in the
same regression formula.
"""

