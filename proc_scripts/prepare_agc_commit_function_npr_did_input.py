def main() -> int:
    args = parse_args()

    if args.self_test:
        run_self_test()
        print("Self-test: PASS")
        if args.input_table is None:
            return 0

    input_table = require_file(args.input_table, "run-py-7a input table")
    covariate_panel = require_file(args.covariate_panel, "Covariate panel")
    if args.output_dir is None:
        raise ValueError("--output-dir is required for a production run")
    output_dir = args.output_dir
    qc_dir = args.qc_dir or output_dir / "qc"

    prepare_output_directory(output_dir, args.overwrite_output)
    qc_dir.mkdir(parents=True, exist_ok=True)

    outputs = build_outputs(
        input_table,
        covariate_panel,
        args.specification_name,
        {
            "rows": args.expected_rows,
            "positive_rows": args.expected_positive_event_rows,
            "zero_rows": args.expected_zero_event_rows,
            "function_no_selected_rows": (
                args.expected_function_event_no_selected_rows
            ),
            "control_rows": args.expected_control_rows,
            "treatment_rows": args.expected_treatment_rows,
            "parse_exclusion_months": args.expected_parse_exclusion_months,
        },
        {
            "age": args.known_age_missing,
            "contributors": args.known_contributors_missing,
            "stars": args.known_stars_missing,
            "issues": args.known_issues_missing,
            "ncloc_paper": args.known_paper_ncloc_missing,
        },
    )
    summary = write_outputs(
        outputs,
        input_table,
        covariate_panel,
        output_dir,
        qc_dir,
        args.specification_name,
    )

    print("=" * 78)
    print("run-py-7b: prepare NPR commit-function Borusyak DiD inputs")
    print("=" * 78)
    print(f"Status:                                  {summary['status']}")
    print(f"Specification:                           {summary['specification']}")
    print(f"Full panel rows:                         {summary['full_panel_rows']}")
    print(f"Conditional-ratio panel rows:            {summary['ratio_panel_rows']}")
